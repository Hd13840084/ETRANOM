export function getCharacterAtlasPlaybackProfileV2133(specializationId, state, direction) {
  const key = `${String(specializationId || '').trim()}/${String(state || 'idle')}/${String(direction || 'south').toLowerCase().replaceAll('_', '-')}`;
  if (state === 'walk' && WALK_TWO_CYCLE.has(key.replace('/walk/', '/'))) {
    return Object.freeze({ frameIndices: Object.freeze([0, 1, 2, 3]), fps: 6, cycleDurationMs: 1000 / 1.5, normalizedTwoCycle: true });
  }
  if (state === 'run' && RUN_TWO_CYCLE.has(key.replace('/run/', '/'))) {
    return Object.freeze({ frameIndices: Object.freeze([0, 1, 2, 3]), fps: 10, cycleDurationMs: 1000 / 2.5, normalizedTwoCycle: true });
  }
  return null;
}
