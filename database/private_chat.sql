-- ETRANOM Phase 2: private messaging between accepted friends only.
-- Run once in Supabase SQL Editor after the friends tables/functions are installed.
create table if not exists public.private_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint private_messages_no_self check (sender_id <> receiver_id)
);

create index if not exists private_messages_pair_created_idx
  on public.private_messages (sender_id, receiver_id, created_at desc);
create index if not exists private_messages_receiver_created_idx
  on public.private_messages (receiver_id, created_at desc);

alter table public.private_messages enable row level security;
revoke all on public.private_messages from anon;
grant select, insert on public.private_messages to authenticated;
grant usage, select on sequence public.private_messages_id_seq to authenticated;

drop policy if exists "chat participants can read messages" on public.private_messages;
create policy "chat participants can read messages"
on public.private_messages for select to authenticated
using (auth.uid() = sender_id or auth.uid() = receiver_id);

drop policy if exists "friends can send private messages" on public.private_messages;
create policy "friends can send private messages"
on public.private_messages for insert to authenticated
with check (
  auth.uid() = sender_id
  and exists (
    select 1 from public.friendships f
    where (f.user_low = auth.uid() and f.user_high = receiver_id)
       or (f.user_high = auth.uid() and f.user_low = receiver_id)
  )
);

-- Add to Supabase Realtime publication only if it is not already present.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'private_messages'
     ) then
    alter publication supabase_realtime add table public.private_messages;
  end if;
end $$;
