-- ETRANOM Phase 2: one global world chat shared by all authenticated players.
-- Run once in Supabase SQL Editor after player_profiles has been created.
create table if not exists public.global_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'مسافر بی‌نام',
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists global_messages_created_idx
  on public.global_messages (created_at desc);

alter table public.global_messages enable row level security;
revoke all on public.global_messages from anon;
grant select, insert on public.global_messages to authenticated;
grant usage, select on sequence public.global_messages_id_seq to authenticated;

drop policy if exists "authenticated players can read global chat" on public.global_messages;
create policy "authenticated players can read global chat"
on public.global_messages for select to authenticated
using (auth.uid() is not null);

drop policy if exists "players can post as themselves to global chat" on public.global_messages;
create policy "players can post as themselves to global chat"
on public.global_messages for insert to authenticated
with check (auth.uid() = sender_id);

-- The display name is taken from the server-side player profile, never trusted from the client.
create or replace function public.etranom_global_chat_prepare_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  profile_name text;
  last_message timestamptz;
begin
  if auth.uid() is null or new.sender_id <> auth.uid() then
    raise exception 'global_chat_auth_required';
  end if;

  select coalesce(nullif(btrim(display_name), ''), nullif(btrim(username), ''), 'مسافر بی‌نام')
    into profile_name
    from public.player_profiles
    where user_id = new.sender_id;
  new.display_name := coalesce(profile_name, 'مسافر بی‌نام');

  select created_at into last_message
    from public.global_messages
    where sender_id = new.sender_id
    order by created_at desc
    limit 1;
  if last_message is not null and last_message > now() - interval '2 seconds' then
    raise exception 'global_chat_rate_limit';
  end if;

  return new;
end;
$$;

drop trigger if exists etranom_global_chat_prepare on public.global_messages;
create trigger etranom_global_chat_prepare
before insert on public.global_messages
for each row execute function public.etranom_global_chat_prepare_message();

-- Add to Supabase Realtime publication only when not already present.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'global_messages'
     ) then
    alter publication supabase_realtime add table public.global_messages;
  end if;
end $$;
