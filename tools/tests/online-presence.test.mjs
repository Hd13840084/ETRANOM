import assert from 'node:assert/strict';
import { ETRANOMPresence } from '../../systems/online/presence.js';
const listeners = new Map();
globalThis.document = { visibilityState:'visible', addEventListener:(n,f)=>listeners.set('d'+n,f), removeEventListener:(n)=>listeners.delete('d'+n) };
globalThis.window = { addEventListener:(n,f)=>listeners.set('w'+n,f), removeEventListener:(n)=>listeners.delete('w'+n) };
let handlers={}; let tracked=[]; let removed=0;
const state={};
const channel={on(type,filter,fn){handlers[filter.event]=fn;return this;},subscribe(fn){this.sub=fn;queueMicrotask(()=>fn('SUBSCRIBED'));return this;},async track(meta){tracked.push(meta);return {error:null};},presenceState(){return state;}};
const client={channel(){return channel;},async removeChannel(){removed++;return 'ok';}};
const updates=[];
const p=new ETRANOMPresence(client,{id:'user-A'},x=>updates.push(x),{heartbeatMs:60000});
await p.start();
assert.equal(p.state,'SUBSCRIBED');
assert.equal(tracked.length,1);
assert.equal(p.setLocation({world_id:'starting_world',region_id:'burnt_forest',x:-700,y:1800,display_name:'بازیکن آزمایشی',player_level:3,player_class:'جادوگر'},true),true);
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(tracked.at(-1).world_id,'starting_world');
assert.equal(tracked.at(-1).region_id,'burnt_forest');
state['user-A']=[{user_id:'user-A',last_seen:'2026-01-01T00:00:00Z'},{user_id:'user-A',last_seen:'2026-01-02T00:00:00Z'}];
state['user-B']=[{user_id:'user-A',last_seen:'2026-01-02T00:00:00Z'}];
state['user-C']=[{user_id:'user-A',last_seen:'2026-01-03T00:00:00Z'}];
handlers.sync();
assert.equal(p.online.size,3);
assert.equal(p.sessionCount,4);
assert.equal(p.isOnline('user-B'),true);
assert.equal(p.isOnline('user-C'),true);
assert.equal(p.getUser('user-A').last_seen,'2026-01-02T00:00:00Z');
await p.stop();
assert.equal(p.state,'STOPPED');
assert.equal(p.online.size,0);
assert.equal(removed,1);
assert.equal(listeners.size,0);
console.log('Presence lifecycle and aggregation tests passed.');
