import { readFileSync, existsSync } from 'node:fs';
import assert from 'node:assert/strict';
const root = new URL('../../', import.meta.url);
const html = readFileSync(new URL('index.html', root), 'utf8');
assert.ok(existsSync(new URL('systems/classes/warlock.js', root)), 'Warlock module must ship with the repository');
assert.match(html, /warlock\.js\?v=125/);
assert.match(html, /catch \(warlockLoadError\)/, 'a missing Warlock asset must not block login');
assert.match(html, /continuing without blocking login/);
assert.match(html, /game\.js\?v=125/);
console.log('Warlock login asset recovery v125: PASS');
