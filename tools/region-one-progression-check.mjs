import fs from 'node:fs';
const source=fs.readFileSync(new URL('../game.js',import.meta.url),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
assert(source.includes('state.selectedDangerRegion=regionId'),'Combat must persist the selected danger zone');
assert(source.includes('combatStart({regionId:id})'),'Normal battle must pass the exact selected zone ID');
assert(source.includes('combatStart({regionId:e.regionId,encounterId:e.id})'),'Mini-boss/boss must pass their owning zone ID');
assert(source.includes('bonus.hp=(bonus.hp||0)+Math.max(1,Math.round(base*20))'),'Crafted gear must scale HP');
assert(source.includes('bonus.mp=(bonus.mp||0)+Math.max(1,Math.round(base*18))'),'Crafted gear must scale MP');
assert(source.includes('vitality*1000'),'Vitality must scale maximum HP');
assert(source.includes('intellect*800+faith*600'),'Intellect/Faith must scale maximum MP');
assert(source.includes('characterStat("perception")+(Number(gear.perception)||0))*.35'),'Perception must contribute to magic/faith attack');
const regionBlock=source.match(/const ETRANOM_REGION_CONTENT=\[([\s\S]*?)\n  \];/);
assert(regionBlock,'Region 1 zone catalog missing');
const zones=[...regionBlock[1].matchAll(/\{id:"([^"]+)"[^}]*?recipeLevel:1/g)].map(x=>x[1]);
assert(zones.length===6,'All six Region 1 zones must explicitly produce item level 1 recipes');
const recipeScale=3.5**9,highTierBase=6*4.2*recipeScale;
const oneMythicItemHp=highTierBase*20,oneMythicItemMp=highTierBase*18;
assert(oneMythicItemHp>10_000_000&&oneMythicItemMp>10_000_000,'Level 10 mythic equipment scaling must support the 10M HP/MP endgame target');
console.log(`Region 1 progression checks passed: ${zones.length} zones -> recipe level 1; level-10 mythic item HP bonus ~${Math.round(oneMythicItemHp).toLocaleString('en-US')}, MP bonus ~${Math.round(oneMythicItemMp).toLocaleString('en-US')}.`);
