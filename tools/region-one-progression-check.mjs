import fs from 'node:fs';
const source=fs.readFileSync(new URL('../game.js',import.meta.url),'utf8');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
assert(source.includes('state.selectedDangerRegion=regionId'),'Combat must persist the selected danger zone');
assert(source.includes('combatStart({regionId:id})'),'Normal battle must pass the exact selected zone ID');
assert(source.includes('combatStart({regionId:e.regionId,encounterId:e.id})'),'Mini-boss/boss must pass their owning zone ID');
assert(source.includes('bonus.hp=(bonus.hp||0)+Math.max(1,Math.round(base*3))'),'Crafted gear must scale HP');
assert(source.includes('bonus.mp=(bonus.mp||0)+Math.max(1,Math.round(base*3))'),'Crafted gear must scale MP');
assert(source.includes('vitality*10'),'Vitality must scale maximum HP');
assert(source.includes('intellect*8+(faithClass?faith*8:0)'),'Intellect/Faith must scale maximum MP');
assert(source.includes('const hitChance=clamp(85+(characterStat("perception")+(Number(gear.perception)||0)-10)*.35,65,98)'),'Perception must improve hit accuracy');
const regionBlock=source.match(/const ETRANOM_REGION_CONTENT=\[([\s\S]*?)\n  \];/);
assert(regionBlock,'Region 1 zone catalog missing');
const zones=[...regionBlock[1].matchAll(/\{id:"([^"]+)"[^}]*?recipeLevel:1/g)].map(x=>x[1]);
assert(zones.length===6,'All six Region 1 zones must explicitly produce item level 1 recipes');
const recipeScale=3**9,sumSlotBases=48;
const fullSetHp=sumSlotBases*4.2*recipeScale*3,fullSetMp=sumSlotBases*4.2*recipeScale*3;
assert(fullSetHp>10_000_000&&fullSetMp>10_000_000,'A full level-10 mythic equipment set must support the 10M HP/MP endgame target');
console.log(`Region 1 progression checks passed: ${zones.length} zones -> recipe level 1; projected full level-10 mythic set HP ~${Math.round(fullSetHp).toLocaleString('en-US')}, MP ~${Math.round(fullSetMp).toLocaleString('en-US')}.`);
